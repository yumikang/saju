/**
 * 한자의 인기도 레벨 판정
 */
export type PopularityLevel = 'very' | 'popular' | 'moderate' | 'traditional' | 'rare' | 'unknown';

export function getPopularityLevel(char: string): PopularityLevel {
  const veryPopular = [...VERY_POPULAR_MALE_HANJA, ...VERY_POPULAR_FEMALE_HANJA];
  if (veryPopular.includes(char)) {
    return 'very';
  }

  const popular = [...POPULAR_MALE_HANJA, ...POPULAR_FEMALE_HANJA];
  if (popular.includes(char)) {
    return 'popular';
  }

  const moderate = [...MODERATE_POPULARITY_HANJA];
  if (moderate.includes(char)) {
    return 'moderate';
  }

  const traditional = [...TRADITIONAL_NAMING_HANJA];
  if (traditional.includes(char)) {
    return 'traditional';
  }

  const rare = [...RARE_HANJA];
  if (rare.includes(char)) {
    return 'rare';
  }

  return 'unknown';
}

/**
 * 한자가 현대적이고 인기 있는지 체크
 */
export function isModernPopularHanja(char: string): boolean {
  const level = getPopularityLevel(char);
  return level === 'very' || level === 'popular' || level === 'moderate';
}

/**
 * 한자가 작명에 적합한지 체크 (드문 한자 제외)
 */
export function isSuitableForNaming(char: string): boolean {
  const level = getPopularityLevel(char);
  return level !== 'rare';
}

/**
 * 인기도 점수 산정 (0-100)
 */
export function getPopularityScore(char: string): number {
  const level = getPopularityLevel(char);

  switch (level) {
    case 'very':
      return 100;
    case 'popular':
      return 90;
    case 'moderate':
      return 70;
    case 'traditional':
      return 50;
    case 'rare':
      return 10;
    default:
      return 0;
  }
}

